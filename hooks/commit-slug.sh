#!/bin/sh
# Подсказка про слаг задачи в коммите (PreToolUse на Bash). Коммит НЕ блокирует: у чужого
# проекта может быть свой формат коммитов, и хук не должен мешать работе. Если в тексте
# команды нет слага задачи (PROJ-42) и его нет в имени ветки — одна строка агенту.
# Ничего не пишет в файлы проекта, в сеть не ходит.

input="$(cat)"

# JSON-строка из прозы: переводы строк и табы в пробелы, кавычки и слэши вычищены —
# так результат валиден на любом sed, а невалидный ответ харнесс молча выбросил бы.
json_str() {
  printf '%s' "$1" | tr '\n\r\t' '   ' | sed "s/\\\\/ /g; s/\"/'/g; s/^/\"/; s/\$/\"/"
}

tool="$(printf '%s' "$input" | sed -n 's/.*"tool_name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n1)"
[ "$tool" = "Bash" ] || exit 0

# Ровно одно значение поля command, с учётом экранирования; переводы строк — в `;`,
# потому что в многострочной команде это такой же разделитель команд.
cmd="$(printf '%s' "$input" | grep -oE '"command"[[:space:]]*:[[:space:]]*"([^"\\]|\\.)*"' | head -n1 |
  sed 's/^"command"[[:space:]]*:[[:space:]]*"//; s/"$//')"
cmd="$(printf '%s' "$cmd" | sed 's/\\n/;/g; s/\\"/"/g; s/\\\\/\\/g')"
[ -n "$cmd" ] || exit 0

# Коммитом считаем вызов `git commit` в позиции команды, а не упоминание этих слов в тексте.
printf '%s' "$cmd" | grep -qE '(^|[;&|(){])[[:space:]]*([A-Za-z_][A-Za-z0-9_]*=[^[:space:]]*[[:space:]]+)*git([[:space:]]+-[Cc][[:space:]]+[^[:space:]]+)*[[:space:]]+commit([[:space:]]|$)' || exit 0

SLUG='[A-Z][A-Z0-9]+-[0-9]+'

# Слаг в тексте команды: сообщение через -m, heredoc или трейлер — тишина.
printf '%s' "$cmd" | grep -qE "$SLUG" && exit 0

# Сообщение из файла (-F <файл>) — заглянем в файл, если он читается.
msgfile="$(printf '%s' "$cmd" | sed -n 's/.*[[:space:]]-F[[:space:]][[:space:]]*\([^[:space:];&|]*\).*/\1/p' | head -n1)"
if [ -n "$msgfile" ] && [ "$msgfile" != "-" ] && [ -r "$msgfile" ]; then
  grep -qE "$SLUG" "$msgfile" && exit 0
fi

# Сообщения в команде нет совсем (откроется редактор, --amend без -m) — текста не видим,
# гадать не будем.
printf '%s' "$cmd" | grep -qE '(^|[[:space:]])(-m|--message|-F|--file)([[:space:]=]|$)' || exit 0

# Слаг в имени ветки — задача известна, тишина.
branch="$(git rev-parse --abbrev-ref HEAD 2>/dev/null)"
printf '%s' "$branch" | grep -qE "$SLUG" && exit 0

printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","additionalContext":%s}}\n' \
  "$(json_str "В сообщении коммита нет слага задачи вида PROJ-42, и в имени ветки его нет. Если коммит по задаче Taskless — добавь слаг в сообщение, а если у проекта свой формат коммитов — трейлером Task: PROJ-42 или в описание PR. Коммит не блокирую.")"
exit 0

#!/bin/sh
# Stop-хук роя: надзор не должен обрываться концом хода (TASWM-592, runbook роя §4).
# Если сессия — про рой (в недавнем окне транскрипта есть swarm-туры MCP), а уходящий ход
# не звал swarm_wait_event — ход не отпускаем, просим продолжить цикл надзора.
# Подпись имени тула — по окончанию (swarm_wait_event): сервер бывает mcp__taskless__
# или mcp__<uuid>__ (28.09), полный список имён ненадёжен.
#
# Выход: строгий JSON (ZCode сырой stdout молча выбрасывает — см. session-start.sh).
# Fail-open: нет jq/файла/связи с роем — молчим, работа агента важнее напоминания.

input=$(cat)

# Повторный вызов после нашего же block — не зацикливаемся.
[ "$(printf '%s' "$input" | jq -r '.stop_hook_active // false' 2>/dev/null)" = "true" ] && exit 0

t=$(printf '%s' "$input" | jq -r '.transcript_path // empty' 2>/dev/null)
[ -n "$t" ] && [ -f "$t" ] || exit 0

# Ищем ВЫЗОВ тула, а не упоминание в тексте (runbook §4: оркестратор пишет про
# swarm_wait_event постоянно, голый grep по имени давал бы ложные срабатывания):
# сигнатура "name":"<сервер>swarm_wait_event" живёт только в блоках tool_use.
# Формат-агностично (Claude/ZCode/rollout пишут её одинаково), без jq-схем.

# 1) Этот ход уже звал swarm_wait_event? Окно грубое (250 строк) — точная граница хода
#    дважды давала ложную тревогу (runbook §4): транскрипт растёт под хуком.
tail -n 250 "$t" 2>/dev/null | grep -q '"name":"[^"]*swarm_wait_event"' && exit 0

# 2) Сессия вообще про рой? Широкое окно (2000 строк) ищет ЛЮБОЙ swarm-тур:
#    нет их — человек просто работает с трекером, напоминать не о чем.
tail -n 2000 "$t" 2>/dev/null | grep -qE '"name":"[^"]*swarm_(wait_event|attention|list_runs|run_upsert|host_command)"' || exit 0

json_str() {
  printf '%s' "$1" | tr '\n\r\t' '   ' | sed "s/\\\\/ /g; s/\"/'/g; s/^/\"/; s/\$/\"/"
}

printf '{"decision":"block","reason":%s}\n' \
  "$(json_str "Сессия работает с роем, а в этом ходе не было swarm_wait_event — надзор встанет до следующего слова человека. Продолжи цикл: swarm_wait_event с курсором, разбери события (вопросы дронов — swarm_answer, упавших — логом и wake), затем снова ожидание. Если следить вправду незачем — скажи это явно в ответе, а не молча завершай ход.")"
